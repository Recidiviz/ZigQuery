/// A `spec.Type` for a leaf kind. `kind` is the raw `pb.TypeKind` int, which is
/// what `typeKind()` reads back.
fn leaf(kind: zetasqlite.pb.TypeKind) spec.Type {
    return .{ .kind = @intFromEnum(kind) };
}

/// Encodes one value and compares against the reference bytes.
fn expectDatum(want: []const u8, typ: *const spec.Type, v: Value, nullable: bool) !void {
    var w = avro.Writer.init(testing.allocator);
    defer w.deinit();
    try avro.writeField(&w, typ, v, nullable);
    try testing.expectEqualSlices(u8, want, w.bytes());
}

test "integers are zigzag varints" {
    const t = leaf(.TYPE_INT64);
    try expectDatum(golden.long_zero, &t, .{ .int = 0 }, false);
    try expectDatum(golden.long_one, &t, .{ .int = 1 }, false);
    try expectDatum(golden.long_minus_one, &t, .{ .int = -1 }, false);
    // 64 is the first value needing a continuation byte.
    try expectDatum(golden.long_64, &t, .{ .int = 64 }, false);
    try expectDatum(golden.long_min, &t, .{ .int = std.math.minInt(i64) }, false);
    try expectDatum(golden.long_max, &t, .{ .int = std.math.maxInt(i64) }, false);
}

test "the other primitives" {
    const b = leaf(.TYPE_BOOL);
    try expectDatum(golden.bool_true, &b, .{ .bool = true }, false);
    try expectDatum(golden.bool_false, &b, .{ .bool = false }, false);

    const d = leaf(.TYPE_DOUBLE);
    try expectDatum(golden.double_1_5, &d, .{ .float = 1.5 }, false);
    try expectDatum(golden.double_neg, &d, .{ .float = -3.25 }, false);

    const s = leaf(.TYPE_STRING);
    try expectDatum(golden.string_hello, &s, .{ .string = "hello" }, false);
    try expectDatum(golden.string_empty, &s, .{ .string = "" }, false);
    // The length prefix counts bytes, not codepoints.
    try expectDatum(golden.string_utf8, &s, .{ .string = "héllo→" }, false);

    const by = leaf(.TYPE_BYTES);
    try expectDatum(golden.bytes_nul, &by, .{ .bytes = "\x00\xff" }, false);
}

test "a nullable column leads with its branch index" {
    // The single highest-risk thing in this file. Writing 1 for null and 0 for
    // a value produces a buffer that decodes cleanly into wrong values.
    const t = leaf(.TYPE_INT64);
    try expectDatum(golden.nullable_long_null, &t, .null, true);
    try expectDatum(golden.nullable_long_value, &t, .{ .int = -2 }, true);

    // A REQUIRED column has no union, so the same value encodes shorter.
    try expectDatum(golden.long_minus_one, &t, .{ .int = -1 }, false);
}

test "a null in a REQUIRED column has nowhere to go" {
    // The schema for a REQUIRED column is a bare type: there is no branch to
    // write. Silently emitting the zero value would corrupt the row.
    const t = leaf(.TYPE_INT64);
    var w = avro.Writer.init(testing.allocator);
    defer w.deinit();
    try testing.expectError(error.TypeMismatch, avro.writeField(&w, &t, .null, false));
}

test "temporal kinds keep their own units" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    // DATE is days since the epoch, as a 32-bit int -- not the unix seconds
    // `Value.toInt64` would rescale it to.
    const dt = leaf(.TYPE_DATE);
    try expectDatum(golden.int_date_epoch, &dt, .{ .date = 0 }, false);

    // DATETIME is the odd one: BigQuery sends a string, with a `T` separator.
    const dtt = leaf(.TYPE_DATETIME);
    const micros = try value_mod.parseDatetimeMicros("2026-01-01 12:00:00.123456");
    try expectDatum(golden.datetime_string, &dtt, .{ .datetime = micros }, false);
    _ = a;
}

test "decimals are minimal-length big-endian two's complement" {
    // Neither stored form is reusable: codec_binary is little-endian at a fixed
    // width, codec_sortable is big-endian but sign-bit-XORed for memcmp.
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    const n = leaf(.TYPE_NUMERIC);
    try expectDatum(
        golden.numeric_1_2345,
        &n,
        try value_mod.numericFromString(a, "1.2345", false),
        false,
    );
    // Zero is one 0x00 byte, not zero bytes.
    try expectDatum(golden.numeric_zero, &n, try value_mod.numericFromString(a, "0", false), false);
    try expectDatum(
        golden.numeric_neg,
        &n,
        try value_mod.numericFromString(a, "-1.5", false),
        false,
    );
    try expectDatum(
        golden.numeric_max,
        &n,
        try value_mod.numericFromString(a, "99999999999999999999999999999.999999999", false),
        false,
    );

    // BIGNUMERIC differs only by scale (38, not 9), so the same -1.5 is a much
    // larger unscaled integer.
    const bn = leaf(.TYPE_BIGNUMERIC);
    try expectDatum(
        golden.bignumeric_neg_1_5,
        &bn,
        try value_mod.numericFromString(a, "-1.5", true),
        false,
    );
}

test "arrays are a counted block and a terminator" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var elem = leaf(.TYPE_INT64);
    var arr: spec.Type = .{ .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_ARRAY), .element_type = &elem };

    // An empty array is the terminator alone -- no zero-count block first.
    try expectDatum(golden.array_empty, &arr, try value_mod.arrayValue(a, &.{}), false);
    try expectDatum(golden.array_one, &arr, try value_mod.arrayValue(a, &.{.{ .int = 7 }}), false);
    try expectDatum(
        golden.array_three,
        &arr,
        try value_mod.arrayValue(a, &.{ .{ .int = 1 }, .{ .int = 2 }, .{ .int = 3 } }),
        false,
    );
}

test "a top-level BOOL arrives as .int, one inside an array as .bool" {
    // The trap the whole file is arranged around. `encoder.encodeTo` stores a
    // top-level bool as a SQLite integer, so `nextTyped` hands back `.int`;
    // nested in a composite it round-trips through codec_binary and comes back
    // `.bool`. Both must encode to the same Avro boolean, which only happens
    // because the encoder dispatches on the declared type.
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    const b = leaf(.TYPE_BOOL);
    try expectDatum(golden.bool_true, &b, .{ .int = 1 }, false);
    try expectDatum(golden.bool_false, &b, .{ .int = 0 }, false);
    try expectDatum(golden.bool_true, &b, .{ .bool = true }, false);

    var elem = leaf(.TYPE_BOOL);
    var arr: spec.Type = .{ .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_ARRAY), .element_type = &elem };
    try expectDatum(
        golden.array_bool,
        &arr,
        try value_mod.arrayValue(a, &.{ .{ .bool = true }, .{ .bool = false } }),
        false,
    );
}

test "a struct is its fields concatenated, each with its own branch" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var ta = leaf(.TYPE_INT64);
    var tb = leaf(.TYPE_STRING);
    var fa: spec.NameWithType = .{ .name = "a", .type = &ta };
    var fb: spec.NameWithType = .{ .name = "b", .type = &tb };
    var fields = [_]*spec.NameWithType{ &fa, &fb };
    var st: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_STRUCT),
        .field_types = &fields,
    };

    try expectDatum(
        golden.struct_a_b,
        &st,
        try value_mod.structValue(a, &.{ "a", "b" }, &.{ .{ .int = 1 }, .{ .string = "x" } }),
        false,
    );
}

test "INTERVAL is a record, not Avro's duration" {
    // Recorded from BigQuery: years fold into months, everything below days
    // folds into microseconds. Avro's own `duration` is a fixed(12) of unsigned
    // little-endian fields and could not carry a negative interval anyway.
    const t = leaf(.TYPE_INTERVAL);
    try expectDatum(
        golden.interval_1y2m3d,
        &t,
        .{ .interval = try value_mod.parseIntervalValue("1-2 3 4:5:6") },
        false,
    );
}

test "RANGE is a record whose UNBOUNDED bounds are nulls" {
    var elem = leaf(.TYPE_DATE);
    var rng: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_RANGE),
        .element_type = &elem,
    };

    try expectDatum(golden.range_date, &rng, value_mod.rangeValue(.date, 20454, 20485), false);
    // Both bounds unbounded: two null branches, and nothing else.
    try expectDatum(
        golden.range_date_unbounded,
        &rng,
        value_mod.rangeValue(.date, null, null),
        false,
    );
}

test "decimalBytes trims only redundant sign bytes" {
    // The trimming rule is where an off-by-one silently changes the value: a
    // leading 0x00 may only go if the next byte's top bit is clear, or the
    // number turns negative.
    var buf: [32]u8 = undefined;
    try testing.expectEqualSlices(u8, &.{0x00}, avro.decimalBytes(&buf, 0));
    try testing.expectEqualSlices(u8, &.{0x01}, avro.decimalBytes(&buf, 1));
    try testing.expectEqualSlices(u8, &.{0xff}, avro.decimalBytes(&buf, -1));
    try testing.expectEqualSlices(u8, &.{0x7f}, avro.decimalBytes(&buf, 127));
    // 128 needs a leading zero byte or it reads as -128.
    try testing.expectEqualSlices(u8, &.{ 0x00, 0x80 }, avro.decimalBytes(&buf, 128));
    try testing.expectEqualSlices(u8, &.{0x80}, avro.decimalBytes(&buf, -128));
    try testing.expectEqualSlices(u8, &.{ 0xff, 0x7f }, avro.decimalBytes(&buf, -129));
}

// ---- the schema, against the one BigQuery really sent ----

fn schemaOf(a: std.mem.Allocator, cols: []const avro.Column) ![]const u8 {
    return avro.schemaJson(a, cols);
}

test "each leaf type gets the logical type BigQuery uses" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    // Expected strings lifted from testdata/storage/bigquery_avro_schema.json,
    // which was recorded from the real service.
    const cases = [_]struct { kind: zetasqlite.pb.TypeKind, want: []const u8 }{
        .{ .kind = .TYPE_INT64, .want = "\"long\"" },
        .{ .kind = .TYPE_DOUBLE, .want = "\"double\"" },
        .{ .kind = .TYPE_BOOL, .want = "\"boolean\"" },
        .{ .kind = .TYPE_STRING, .want = "\"string\"" },
        .{ .kind = .TYPE_BYTES, .want = "\"bytes\"" },
        .{ .kind = .TYPE_DATE, .want = "{\"type\":\"int\",\"logicalType\":\"date\"}" },
        .{ .kind = .TYPE_TIME, .want = "{\"type\":\"long\",\"logicalType\":\"time-micros\"}" },
        .{
            .kind = .TYPE_TIMESTAMP,
            .want = "{\"type\":\"long\",\"logicalType\":\"timestamp-micros\"}",
        },
        .{ .kind = .TYPE_DATETIME, .want = "{\"type\":\"string\",\"logicalType\":\"datetime\"}" },
        .{ .kind = .TYPE_JSON, .want = "{\"type\":\"string\",\"sqlType\":\"JSON\"}" },
        .{ .kind = .TYPE_GEOGRAPHY, .want = "{\"type\":\"string\",\"sqlType\":\"GEOGRAPHY\"}" },
        .{
            .kind = .TYPE_NUMERIC,
            .want = "{\"type\":\"bytes\",\"logicalType\":\"decimal\",\"precision\":38,\"scale\":9}",
        },
        .{
            .kind = .TYPE_BIGNUMERIC,
            .want = "{\"type\":\"bytes\",\"logicalType\":\"decimal\",\"precision\":77,\"scale\":38}",
        },
    };

    for (cases) |case| {
        var t = leaf(case.kind);
        const got = try schemaOf(a, &.{.{ .name = "c", .type = &t, .nullable = false }});
        const want = try std.fmt.allocPrint(
            a,
            "{{\"type\":\"record\",\"name\":\"__root__\",\"fields\":" ++
                "[{{\"name\":\"c\",\"type\":{s}}}]}}",
            .{case.want},
        );
        try testing.expectEqualStrings(want, got);
    }
}

test "REQUIRED is a bare type and NULLABLE is a union with null first" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var t = leaf(.TYPE_INT64);
    try testing.expectEqualStrings(
        "{\"type\":\"record\",\"name\":\"__root__\",\"fields\":[{\"name\":\"c\",\"type\":\"long\"}]}",
        try schemaOf(a, &.{.{ .name = "c", .type = &t, .nullable = false }}),
