test "a whole row encodes exactly as a reference reader expects" {
    // The gate for this stage. Every field above is checked in isolation; this
    // is the one that catches a schema and an encoder that disagree about
    // whether a field carries a union at all, which desyncs every field after
    // the mismatched one.
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var f: FullRow = undefined;
    f.init();

    const vals = [_]Value{
        .{ .int = 7 },
        .{ .int = -2 },
        .{ .float = 1.5 },
        try value_mod.numericFromString(a, "1.2345", false),
        try value_mod.numericFromString(a, "-1.5", true),
        // A top-level BOOL arrives as .int; the declared type is what makes it
        // an Avro boolean.
        .{ .int = 1 },
        .{ .string = "hello" },
        .{ .bytes = "\x00\xff" },
        .{ .date = 20454 },
        .{ .datetime = try value_mod.parseDatetimeMicros("2026-01-01 12:00:00.123456") },
        .{ .time = try value_mod.parseTimeMicros("12:00:00.123456") },
        .{ .timestamp = 1767225600000123 },
        .{ .json = "{\"a\":1}" },
        .{ .interval = try value_mod.parseIntervalValue("1-2 3 4:5:6") },
        value_mod.rangeValue(.date, 20454, 20485),
        try value_mod.arrayValue(a, &.{ .{ .int = 1 }, .{ .int = 2 }, .{ .int = 3 } }),
        try value_mod.structValue(a, &.{ "a", "b" }, &.{ .{ .int = 1 }, .{ .string = "x" } }),
    };

    var w = avro.Writer.init(a);
    for (f.cols, vals) |col, v| try avro.writeField(&w, col.type, v, col.nullable);
    try testing.expectEqualSlices(u8, golden.full_row, w.bytes());
}

test "a nullable ARRAY has no union, and a null one is an empty array" {
    // The regression. BigQuery emits a bare `{"type":"array",...}` for a
    // REPEATED field whatever its mode, so there is no branch index to write --
    // and no way to spell a NULL array either, which BigQuery answers by
    // treating an empty repeated field as an empty array rather than an absent
    // one.
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var elem = leaf(.TYPE_INT64);
    var arr: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_ARRAY),
        .element_type = &elem,
    };

    // Nullable or not, the bytes are the same: no branch index either way.
    const items = try value_mod.arrayValue(a, &.{ .{ .int = 1 }, .{ .int = 2 }, .{ .int = 3 } });
    try expectDatum(golden.array_three, &arr, items, true);
    try expectDatum(golden.array_three, &arr, items, false);

    // And a NULL array is the empty one, not a null branch.
    try expectDatum(golden.array_empty, &arr, .null, true);

    // The schema agrees: no union in sight.
    try testing.expectEqualStrings(
        "{\"type\":\"record\",\"name\":\"__root__\",\"fields\":" ++
            "[{\"name\":\"c\",\"type\":{\"type\":\"array\",\"items\":\"long\"}}]}",
        try avro.schemaJson(a, &.{.{ .name = "c", .type = &arr, .nullable = true }}),
    );
}
