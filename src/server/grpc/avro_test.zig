//! The Avro encoder against bytes it did not produce.
//!
//! Kept beside `avro.zig` rather than inside it because the golden constants are
//! machine-generated and a regeneration should not disturb hand-written code.
//!
//! Everything that can go wrong in an Avro encoder goes wrong quietly: a union
//! branch index written backwards, a decimal in the wrong byte order, an array
//! missing its terminating block. Each produces bytes a reader accepts and turns
//! into a wrong value. So the expectations here come from fastavro — see
//! `tools/avro_golden.py`, and `uv run tools/avro_golden.py --check` re-derives
//! them — and the type mapping they are built on was recorded from real
//! BigQuery into `testdata/storage/`.

const std = @import("std");
const avro = @import("avro.zig");
const zetasqlite = @import("zetasqlite");
const spec = zetasqlite.spec;
const value_mod = zetasqlite.value;
const Value = value_mod.Value;

const testing = std.testing;

