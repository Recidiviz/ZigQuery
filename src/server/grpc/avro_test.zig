    );
}

test "a REPEATED field is a bare array, and so are its items" {
    // BigQuery does not null-union either the array or its elements, which is
    // consistent with a REPEATED column being unable to hold NULL. Wrapping
    // them would put a branch index in front of every element and desync the
    // whole row.
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var elem = leaf(.TYPE_INT64);
    var arr: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_ARRAY),
        .element_type = &elem,
    };
    try testing.expectEqualStrings(
        "{\"type\":\"record\",\"name\":\"__root__\",\"fields\":" ++
            "[{\"name\":\"c\",\"type\":{\"type\":\"array\",\"items\":\"long\"}}]}",
        try schemaOf(a, &.{.{ .name = "c", .type = &arr }}),
    );
}

test "structs are numbered records and field names are escaped" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    var ta = leaf(.TYPE_INT64);
    // A name needing JSON escaping: the old schema path interpolated raw.
    var fa: spec.NameWithType = .{ .name = "a\"b", .type = &ta };
    var fields = [_]*spec.NameWithType{&fa};
    var st: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_STRUCT),
        .field_types = &fields,
    };
    var st2: spec.Type = .{
        .kind = @intFromEnum(zetasqlite.pb.TypeKind.TYPE_STRUCT),
        .field_types = &fields,
    };

    // Two structs in one schema must not share a record name -- Avro forbids
    // redefining one, so a reader rejects the schema outright.
    const got = try schemaOf(a, &.{
        .{ .name = "s1", .type = &st },
        .{ .name = "s2", .type = &st2 },
    });
    try testing.expect(std.mem.indexOf(u8, got, "\"name\":\"__s_0\"") != null);
    try testing.expect(std.mem.indexOf(u8, got, "\"name\":\"__s_1\"") != null);
    try testing.expect(std.mem.indexOf(u8, got, "\"name\":\"a\\\"b\"") != null);
}

test "RANGE names its record after the element type" {
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
