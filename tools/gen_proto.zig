//! Generates Zig protobuf codecs from a protoc FileDescriptorSet: plain structs
//! plus per-message decode and encode functions over `src/proto/wire.zig`.
//!
//! Run: `zig build gen-proto`, which drives it twice —
//!
//!   proto/googlesql.fdset        -> src/proto/resolved_ast.zig  (engine)
//!   proto/bigquery_storage.fdset -> src/server/proto/storage.zig (server)
//!
//! Both .fdsets are committed, so this only needs rerunning when one of them
//! moves. The two outputs are separate files on purpose; see the self-hosting
//! note below and the comment on the second step in build.zig.
//!
//! `googlesql.fdset`. Only needs rebuilding when the googlesql submodule
//! moves. resolved_ast.proto is generated by Bazel into the external repo tree,
//! whose canonical directory name is version-dependent (googlesql~ on Bazel 7.6,
//! googlesql+ on newer) — discover it rather than hardcoding it:
//!
//!     bazel build -c opt @googlesql//googlesql/resolved_ast:resolved_ast_proto
//!     GS=$(dirname "$(bazel cquery --output=files \
//!         @googlesql//googlesql/resolved_ast:resolved_ast_proto | head -1)")
//!     protoc -I third_party/googlesql -I "$GS/../../.." --include_imports \
//!         --descriptor_set_out=proto/googlesql.fdset "$GS/resolved_ast.proto"
//!
//! `bigquery_storage.fdset`. From googleapis, which is not vendored here — the
//! .fdset is the artifact this repo keeps. A blobless sparse clone is enough:
//!
//!     git clone --depth 1 --filter=blob:none --sparse \
//!         https://github.com/googleapis/googleapis /tmp/googleapis
//!     git -C /tmp/googleapis sparse-checkout set \
//!         google/api google/cloud/bigquery/storage/v1 google/rpc google/type
//!     protoc -I /tmp/googleapis --include_imports \
//!         --descriptor_set_out=proto/bigquery_storage.fdset \
//!         /tmp/googleapis/google/cloud/bigquery/storage/v1/storage.proto
//!
//! Last taken from googleapis 63e5b25d0e0761a1604584b14432aee3783c5862.
//!
//! Representation choices (mirrored by the extractor):
//! - optional scalar field  -> ?T
//! - optional message field -> ?*T (arena-allocated; breaks recursion cycles)
//! - repeated field         -> []T / []*T slice (arena-allocated)
//! - oneof                  -> optional tagged union
//! - enum                   -> non-exhaustive enum(i32) so unknown future values
//!                             decode without error
//! - string/bytes           -> []const u8 borrowing from the input buffer (the
//!                             buffer must outlive the decoded tree; both are
//!                             arena-owned in practice)
//! - unknown fields are skipped; proto2 `required` is not enforced.
//!
//! This generator is self-hosting: `--include_imports` pulled
//! `descriptor.proto` into the .fdset, so the file this writes also contains the
//! `FileDescriptorSet` decoders used to read the .fdset in the first place — the
//! `pb` module is the previous run's output. If a bad .fdset ever produces
//! output that does not compile, the generator can no longer be built to fix it;
//! recover with `git checkout src/proto/resolved_ast.zig`.
//!
//! Ported from the retired `tools/gen_proto.py`, which needed a pip-installed
//! `protobuf` (and the `tools/venv` that came with it). Output is not
//! byte-identical to that script's — `zig build gen-proto` runs `zig fmt` over
//! the result, so this emits structurally correct Zig and lets the formatter
//! decide layout.
const std = @import("std");
const pb = @import("pb");

const Ty = pb.FieldDescriptorProto_Type;

/// Column limit the emitted lines are kept under. `zig fmt` does not reflow
/// long lines, so anything that can overflow has to be split here instead.
const max_cols = 100;

const Error = error{
    /// A descriptor was missing a field protoc always sets.
    MalformedDescriptor,
    /// proto2 `group` fields have no representation here.
    UnsupportedGroup,
    /// --roots named something the .fdset does not define.
    UnknownRoot,
    UnknownType,
} || std.mem.Allocator.Error;

const zig_keywords = std.StaticStringMap(void).initComptime(.{
    .{"align"},          .{"allowzero"}, .{"and"},      .{"anyframe"},
    .{"anytype"},        .{"asm"},       .{"async"},    .{"await"},
    .{"break"},          .{"callconv"},  .{"catch"},    .{"comptime"},
    .{"const"},          .{"continue"},  .{"defer"},    .{"else"},
    .{"enum"},           .{"errdefer"},  .{"error"},    .{"export"},
    .{"extern"},         .{"fn"},        .{"for"},      .{"if"},
    .{"inline"},         .{"noalias"},   .{"noinline"}, .{"nosuspend"},
    .{"opaque"},         .{"or"},        .{"orelse"},   .{"packed"},
    .{"pub"},            .{"resume"},    .{"return"},   .{"linksection"},
    .{"struct"},         .{"suspend"},   .{"switch"},   .{"test"},
    .{"threadlocal"},    .{"try"},       .{"union"},    .{"unreachable"},
    .{"usingnamespace"}, .{"var"},       .{"volatile"}, .{"while"},
    // primitive-ish names that shadow builtins
    .{"type"},           .{"bool"},      .{"true"},     .{"false"},
    .{"null"},           .{"undefined"},
});

/// Field/decl identifier, escaped if it collides with a Zig keyword.
fn zid(a: std.mem.Allocator, name: []const u8) Error![]const u8 {
    if (zig_keywords.has(name) or (name.len > 0 and std.ascii.isDigit(name[0]))) {
        return std.fmt.allocPrint(a, "@\"{s}\"", .{name});
    }
    return name;
}

/// Python's `str.capitalize()`: upper-cases the first character and lower-cases
/// every other one. `foo_BAR` -> `FooBar`, not `FooBAR`.
fn capitalize(a: std.mem.Allocator, word: []const u8) Error![]u8 {
    const buf = try a.alloc(u8, word.len);
    for (word, 0..) |c, i| {
        buf[i] = if (i == 0) std.ascii.toUpper(c) else std.ascii.toLower(c);
    }
    return buf;
}

/// `"".join(p.capitalize() for p in name.split("_")) + "Union"`.
fn oneofUnionName(a: std.mem.Allocator, name: []const u8) Error![]const u8 {
    var buf: std.ArrayList(u8) = .empty;
    var it = std.mem.splitScalar(u8, name, '_');
    while (it.next()) |part| try buf.appendSlice(a, try capitalize(a, part));
    try buf.appendSlice(a, "Union");
    return buf.items;
}

/// The segment after the last `.` of a fully-qualified proto name.
fn lastSegment(fq: []const u8) []const u8 {
    if (std.mem.lastIndexOfScalar(u8, fq, '.')) |i| return fq[i + 1 ..];
    return fq;
}

fn scalarZig(t: Ty) Error![]const u8 {
    return switch (t) {
        .TYPE_DOUBLE => "f64",
        .TYPE_FLOAT => "f32",
        .TYPE_INT64 => "i64",
        .TYPE_UINT64 => "u64",
        .TYPE_INT32 => "i32",
        .TYPE_FIXED64 => "u64",
        .TYPE_FIXED32 => "u32",
        .TYPE_BOOL => "bool",
        .TYPE_STRING => "[]const u8",
        .TYPE_BYTES => "[]const u8",
        .TYPE_UINT32 => "u32",
        .TYPE_SFIXED32 => "i32",
        .TYPE_SFIXED64 => "i64",
        .TYPE_SINT32 => "i32",
        .TYPE_SINT64 => "i64",
        else => error.UnknownType,
    };
}

/// wire.Reader expression producing the raw value for each scalar type, reading
/// from `recv` (`r` for a top-level field, `sub` inside a packed run).
fn scalarRead(a: std.mem.Allocator, t: Ty, recv: []const u8) Error![]const u8 {
    return switch (t) {
        .TYPE_DOUBLE => std.fmt.allocPrint(a, "try {s}.readDouble()", .{recv}),
        .TYPE_FLOAT => std.fmt.allocPrint(a, "try {s}.readFloat()", .{recv}),
        .TYPE_INT64 => std.fmt.allocPrint(a, "try {s}.readInt64()", .{recv}),
        .TYPE_UINT64 => std.fmt.allocPrint(a, "try {s}.readVarint()", .{recv}),
        .TYPE_INT32 => std.fmt.allocPrint(a, "try {s}.readInt32()", .{recv}),
        .TYPE_FIXED64 => std.fmt.allocPrint(a, "try {s}.readFixed64()", .{recv}),
        .TYPE_FIXED32 => std.fmt.allocPrint(a, "try {s}.readFixed32()", .{recv}),
        .TYPE_BOOL => std.fmt.allocPrint(a, "(try {s}.readVarint()) != 0", .{recv}),
        .TYPE_STRING => std.fmt.allocPrint(a, "try {s}.readBytes()", .{recv}),
        .TYPE_BYTES => std.fmt.allocPrint(a, "try {s}.readBytes()", .{recv}),
        .TYPE_UINT32 => std.fmt.allocPrint(a, "@truncate(try {s}.readVarint())", .{recv}),
        .TYPE_SFIXED32 => std.fmt.allocPrint(a, "@bitCast(try {s}.readFixed32())", .{recv}),
        .TYPE_SFIXED64 => std.fmt.allocPrint(a, "@bitCast(try {s}.readFixed64())", .{recv}),
        .TYPE_SINT32 => std.fmt.allocPrint(a, "try {s}.readSint32()", .{recv}),
        .TYPE_SINT64 => std.fmt.allocPrint(a, "try {s}.readSint64()", .{recv}),
        else => error.UnknownType,
    };
}

/// `wire.Writer` method for a singular scalar field: `w.<name>(<num>, v)`.
fn scalarWrite(t: Ty) Error![]const u8 {
    return switch (t) {
        .TYPE_DOUBLE => "writeDouble",
        .TYPE_FLOAT => "writeFloat",
        .TYPE_INT64 => "writeInt64",
        .TYPE_UINT64 => "writeUint",
        .TYPE_INT32 => "writeInt32",
        .TYPE_FIXED64 => "writeFixed64",
        .TYPE_FIXED32 => "writeFixed32",
        .TYPE_BOOL => "writeBool",
        .TYPE_STRING, .TYPE_BYTES => "writeBytes",
        .TYPE_UINT32 => "writeUint",
        .TYPE_SFIXED32 => "writeFixed32",
        .TYPE_SFIXED64 => "writeFixed64",
        .TYPE_SINT32 => "writeSint32",
        .TYPE_SINT64 => "writeSint64",
        else => error.UnknownType,
    };
}

/// The same, inside a packed run where the tag is written once: `w.<name>(v)`.
fn scalarWriteRaw(t: Ty) Error![]const u8 {
    return switch (t) {
        .TYPE_DOUBLE => "writeDoubleRaw",
        .TYPE_FLOAT => "writeFloatRaw",
        .TYPE_INT64 => "writeInt64Raw",
        .TYPE_UINT64 => "writeVarint",
        .TYPE_INT32 => "writeInt32Raw",
        .TYPE_FIXED64 => "writeFixed64Raw",
        .TYPE_FIXED32 => "writeFixed32Raw",
        .TYPE_BOOL => "writeBoolRaw",
        .TYPE_UINT32 => "writeVarint",
        .TYPE_SFIXED32 => "writeFixed32Raw",
        .TYPE_SFIXED64 => "writeFixed64Raw",
        .TYPE_SINT32 => "writeSint32Raw",
        .TYPE_SINT64 => "writeSint64Raw",
        else => error.UnknownType,
