}

/// Two scalar types are narrower in Zig than the writer method that carries
/// them, so the value needs widening at the call site.
fn scalarWriteCast(t: Ty) []const u8 {
    return switch (t) {
        // u32 -> u64 for writeUint/writeVarint.
        .TYPE_UINT32 => "@as(u64, ",
        // i32 -> u32 for writeFixed32, which takes the unsigned form.
        .TYPE_SFIXED32 => "@as(u32, @bitCast(",
        .TYPE_SFIXED64 => "@as(u64, @bitCast(",
        else => "",
    };
}

fn scalarWriteCastClose(t: Ty) []const u8 {
    return switch (t) {
        .TYPE_UINT32 => ")",
        .TYPE_SFIXED32, .TYPE_SFIXED64 => "))",
        else => "",
    };
}

/// Scalars that may appear packed. Mirrors the Python's
/// `set(SCALAR_READ) - {STRING, BYTES}` — note enums are absent from that table,
/// so a repeated enum is only ever decoded unpacked. Preserved deliberately.
fn isPackable(t: Ty) bool {
    return switch (t) {
        .TYPE_DOUBLE,
        .TYPE_FLOAT,
        .TYPE_INT64,
        .TYPE_UINT64,
        .TYPE_INT32,
        .TYPE_FIXED64,
        .TYPE_FIXED32,
        .TYPE_BOOL,
        .TYPE_UINT32,
        .TYPE_SFIXED32,
        .TYPE_SFIXED64,
        .TYPE_SINT32,
        .TYPE_SINT64,
        => true,
        else => false,
    };
}

/// google.protobuf.*Value: proto3 JSON renders these as the bare inner value,
/// so they get a hand-shaped hook rather than the generic object one.
const wrapper_types = std.StaticStringMap(void).initComptime(.{
    .{".google.protobuf.DoubleValue"}, .{".google.protobuf.FloatValue"},
    .{".google.protobuf.Int64Value"},  .{".google.protobuf.UInt64Value"},
    .{".google.protobuf.Int32Value"},  .{".google.protobuf.UInt32Value"},
    .{".google.protobuf.BoolValue"},   .{".google.protobuf.StringValue"},
    .{".google.protobuf.BytesValue"},
});

/// Whatever JSON the client sent. These three carry arbitrary JSON by
/// definition, and std.json.Value already is that, with its own codec.
const json_value_types = std.StaticStringMap(void).initComptime(.{
    .{".google.protobuf.Struct"},    .{".google.protobuf.Value"},
    .{".google.protobuf.ListValue"},
});

/// The json_pb writer for a scalar, or null when std.json's own is right.
fn jsonWriteFn(t: Ty) ?[]const u8 {
    return switch (t) {
        // 64-bit integers are JSON strings.
        .TYPE_INT64, .TYPE_SINT64, .TYPE_SFIXED64 => "writeI64",
        .TYPE_UINT64, .TYPE_FIXED64 => "writeU64",
        .TYPE_BYTES => "writeBytes",
        else => null,
    };
}

/// The json_pb reader for a scalar, and whether it needs the allocator.
fn jsonReadFn(t: Ty) Error![]const u8 {
    return switch (t) {
        .TYPE_DOUBLE => "asF64",
        .TYPE_FLOAT => "asF32",
        .TYPE_INT64, .TYPE_SINT64, .TYPE_SFIXED64 => "asI64",
        .TYPE_UINT64, .TYPE_FIXED64 => "asU64",
        .TYPE_INT32, .TYPE_SINT32, .TYPE_SFIXED32 => "asI32",
        .TYPE_UINT32, .TYPE_FIXED32 => "asU32",
        .TYPE_BOOL => "asBool",
        .TYPE_STRING => "asString",
        .TYPE_BYTES => "asBytes",
        else => error.UnknownType,
    };
}

fn jsonReadTakesAlloc(t: Ty) bool {
    return t == .TYPE_STRING or t == .TYPE_BYTES;
}

const Msg = struct {
    fq: []const u8,
    desc: *pb.DescriptorProto,
    /// Nested-name prefix, e.g. "TypeProto_".
    parent_prefix: []const u8,
};

const Enm = struct {
    fq: []const u8,
    desc: *pb.EnumDescriptorProto,
    parent_prefix: []const u8,
};

const Gen = struct {
    a: std.mem.Allocator,
    msgs: std.StringHashMapUnmanaged(Msg) = .empty,
    enums: std.StringHashMapUnmanaged(Enm) = .empty,
    msg_keys: std.ArrayList([]const u8) = .empty,
    enum_keys: std.ArrayList([]const u8) = .empty,
    /// Fully-qualified proto name -> flat Zig type name.
    names: std.StringHashMapUnmanaged([]const u8) = .empty,
    out: std.ArrayList(u8) = .empty,
    /// JSON codecs only, no binary wire codecs. The REST messages never reach
    /// the wire, and suppressing it keeps `google.protobuf.Struct` — which has
    /// no useful Zig wire form here — out of the encoders.
    json_only: bool = false,

    fn line(g: *Gen, comptime fmt: []const u8, args: anytype) Error!void {
        try g.out.print(g.a, fmt ++ "\n", args);
    }

    // ---- collect ----

    fn collect(g: *Gen, fds: *pb.FileDescriptorSet) Error!void {
        for (fds.file) |f| {
            const pkg: []const u8 = if (f.package) |p|
                (if (p.len > 0) try std.fmt.allocPrint(g.a, ".{s}", .{p}) else "")
            else
                "";
            for (f.message_type) |d| try g.walkMsg(pkg, "", d);
            for (f.enum_type) |e| {
                const name = e.name orelse return error.MalformedDescriptor;
                try g.putEnum(.{
                    .fq = try std.fmt.allocPrint(g.a, "{s}.{s}", .{ pkg, name }),
                    .desc = e,
                    .parent_prefix = "",
                });
            }
        }
    }

    fn walkMsg(g: *Gen, pkg_fq: []const u8, prefix: []const u8, d: *pb.DescriptorProto) Error!void {
        const name = d.name orelse return error.MalformedDescriptor;
        const fq = try std.fmt.allocPrint(g.a, "{s}.{s}", .{ pkg_fq, name });
        try g.putMsg(.{ .fq = fq, .desc = d, .parent_prefix = prefix });

        // Map fields appear as repeated map-entry messages; the entry struct is
        // still generated so decode has a type to target.
        const nested_prefix = try std.fmt.allocPrint(g.a, "{s}{s}_", .{ prefix, name });
        for (d.nested_type) |nested| try g.walkMsg(fq, nested_prefix, nested);
        for (d.enum_type) |e| {
            const ename = e.name orelse return error.MalformedDescriptor;
            try g.putEnum(.{
                .fq = try std.fmt.allocPrint(g.a, "{s}.{s}", .{ fq, ename }),
                .desc = e,
                .parent_prefix = nested_prefix,
            });
        }
    }

    fn putMsg(g: *Gen, m: Msg) Error!void {
        const gop = try g.msgs.getOrPut(g.a, m.fq);
        if (!gop.found_existing) try g.msg_keys.append(g.a, m.fq);
        gop.value_ptr.* = m;
    }

    fn putEnum(g: *Gen, e: Enm) Error!void {
        const gop = try g.enums.getOrPut(g.a, e.fq);
        if (!gop.found_existing) try g.enum_keys.append(g.a, e.fq);
        gop.value_ptr.* = e;
    }

    // ---- prune ----

    /// Restricts the output to the messages and enums reachable from `roots` by
    /// field reference.
    ///
    /// `google/api/*`, `google/type/*` and descriptor.proto arrive through
    /// `--include_imports` as option definitions: reachable as annotations,
    /// never as a field's type, so a closure drops them without naming them.
    /// A root that names nothing is an error, because the alternative is a typo
    /// silently emitting an empty file.
    fn prune(g: *Gen, roots: []const []const u8) Error!void {
        var keep: std.StringHashMapUnmanaged(void) = .empty;
        var stack: std.ArrayList([]const u8) = .empty;
        for (roots) |r| {
            const fq = if (r.len > 0 and r[0] == '.')
                r
            else
                try std.fmt.allocPrint(g.a, ".{s}", .{r});
            if (g.msgs.get(fq) == null and g.enums.get(fq) == null) return error.UnknownRoot;
            try stack.append(g.a, fq);
        }
        while (stack.pop()) |fq| {
            if ((try keep.getOrPut(g.a, fq)).found_existing) continue;
            const m = g.msgs.get(fq) orelse continue;
            for (m.desc.field) |f| {
                const t = f.type orelse continue;
                if (t != .TYPE_MESSAGE and t != .TYPE_ENUM) continue;
                const tn = f.type_name orelse continue;
                if (g.json_only and json_value_types.has(tn)) continue;
                try stack.append(g.a, tn);
            }
        }
        g.msg_keys = try g.retain(g.msg_keys, keep);
        g.enum_keys = try g.retain(g.enum_keys, keep);
    }

    fn retain(
        g: *Gen,
        keys: std.ArrayList([]const u8),
        keep: std.StringHashMapUnmanaged(void),
    ) Error!std.ArrayList([]const u8) {
        var out: std.ArrayList([]const u8) = .empty;
        for (keys.items) |k| {
            if (keep.contains(k)) try out.append(g.a, k);
        }
        return out;
    }

    // ---- naming ----

    /// Maps fully-qualified proto names to flat Zig type names, qualifying with
    /// the package wherever the flat name would collide.
    fn resolveNames(g: *Gen) Error!void {
        var base_count: std.StringHashMapUnmanaged(u32) = .empty;
        for (g.msg_keys.items) |fq| {
            const m = g.msgs.get(fq).?;
            const gop = try base_count.getOrPut(g.a, try g.baseName(m.parent_prefix, fq));
            gop.value_ptr.* = if (gop.found_existing) gop.value_ptr.* + 1 else 1;
        }
        for (g.enum_keys.items) |fq| {
            const e = g.enums.get(fq).?;
            const gop = try base_count.getOrPut(g.a, try g.baseName(e.parent_prefix, fq));
            gop.value_ptr.* = if (gop.found_existing) gop.value_ptr.* + 1 else 1;
        }

        for (g.msg_keys.items) |fq| {
            const m = g.msgs.get(fq).?;
            try g.names.put(g.a, fq, try g.zigName(m.parent_prefix, fq, base_count));
        }
        for (g.enum_keys.items) |fq| {
            const e = g.enums.get(fq).?;
            try g.names.put(g.a, fq, try g.zigName(e.parent_prefix, fq, base_count));
        }
    }

    fn baseName(g: *Gen, parent_prefix: []const u8, fq: []const u8) Error![]const u8 {
        return std.fmt.allocPrint(g.a, "{s}{s}", .{ parent_prefix, lastSegment(fq) });
    }

    fn zigName(
        g: *Gen,
        parent_prefix: []const u8,
        fq: []const u8,
        base_count: std.StringHashMapUnmanaged(u32),
    ) Error![]const u8 {
        const base = try g.baseName(parent_prefix, fq);
        if ((base_count.get(base) orelse 0) <= 1) return base;

        // Qualify with the package (e.g. google.protobuf collisions).
        const without_dot = if (fq.len > 0 and fq[0] == '.') fq[1..] else fq;
        const pkg = if (std.mem.lastIndexOfScalar(u8, without_dot, '.')) |i|
            without_dot[0..i]
        else
            without_dot;
        const flat = try g.a.dupe(u8, pkg);
        std.mem.replaceScalar(u8, flat, '.', '_');
        return std.fmt.allocPrint(g.a, "{s}_{s}", .{ flat, base });
    }

    /// protoc always sets json_name; it is the lowerCamelCase form unless the
    /// .proto overrode it.
    fn jsonName(g: *Gen, f: *pb.FieldDescriptorProto) Error![]const u8 {
        _ = g;
        return f.json_name orelse f.name orelse error.MalformedDescriptor;
    }

    /// The synthetic entry message behind a `map<K,V>` field, or null.
    fn mapEntry(g: *Gen, f: *pb.FieldDescriptorProto) ?*pb.DescriptorProto {
        if (f.label != .LABEL_REPEATED or f.type.? != .TYPE_MESSAGE) return null;
        const m = g.msgs.get(f.type_name orelse return null) orelse return null;
        const opts = m.desc.options orelse return null;
        return if (opts.map_entry orelse false) m.desc else null;
    }

    fn isJsonValue(g: *Gen, f: *pb.FieldDescriptorProto) bool {
        if (!g.json_only) return false;
        const tn = f.type_name orelse return false;
        return json_value_types.has(tn);
    }

    /// Message fields are arena pointers, except the ones carried as
    /// std.json.Value.
    fn isPtrField(g: *Gen, f: *pb.FieldDescriptorProto) bool {
        return f.type.? == .TYPE_MESSAGE and !g.isJsonValue(f);
    }

    fn typeName(g: *Gen, f: *pb.FieldDescriptorProto) Error![]const u8 {
        const tn = f.type_name orelse return error.MalformedDescriptor;
        return g.names.get(tn) orelse error.MalformedDescriptor;
    }

    fn fieldZigType(g: *Gen, f: *pb.FieldDescriptorProto) Error![]const u8 {
        const t = f.type orelse return error.MalformedDescriptor;
        if (g.isJsonValue(f)) return "std.json.Value";
        return switch (t) {
            .TYPE_MESSAGE, .TYPE_ENUM => try g.typeName(f),
            .TYPE_GROUP => error.UnsupportedGroup,
            else => scalarZig(t),
        };
    }

    fn readExpr(g: *Gen, f: *pb.FieldDescriptorProto) Error![]const u8 {
        const t = f.type orelse return error.MalformedDescriptor;
        return switch (t) {
            .TYPE_MESSAGE => std.fmt.allocPrint(
                g.a,
                "try {s}.decodeReader(a, &sub)",
                .{try g.typeName(f)},
            ),
            .TYPE_ENUM => std.fmt.allocPrint(
                g.a,
                "@as({s}, @fromBackingInt(try r.readInt32()))",
                .{try g.typeName(f)},
            ),
            else => scalarRead(g.a, t, "r"),
        };
    }

    // ---- emit ----

    fn genEnum(g: *Gen, e: Enm) Error!void {
        try g.line("pub const {s} = enum(i32) {{", .{g.names.get(e.fq).?});
        var seen: std.AutoHashMapUnmanaged(i32, void) = .empty;
        for (e.desc.value) |v| {
            const number = v.number orelse return error.MalformedDescriptor;
            const name = v.name orelse return error.MalformedDescriptor;
            // allow_alias duplicates: keep the first spelling of each number.
            if ((try seen.getOrPut(g.a, number)).found_existing) continue;
            try g.line("    {s} = {d},", .{ try zid(g.a, name), number });
        }
        try g.line("    _,", .{});
        try g.line("}};", .{});
        try g.line("", .{});
    }

    fn genMessage(g: *Gen, m: Msg) Error!void {
        const zname = g.names.get(m.fq).?;
        const d = m.desc;

        // Partition fields into oneof buckets and plain fields.
        const oneofs = try g.a.alloc(std.ArrayList(*pb.FieldDescriptorProto), d.oneof_decl.len);
        for (oneofs) |*o| o.* = .empty;
        var plain: std.ArrayList(*pb.FieldDescriptorProto) = .empty;
        for (d.field) |f| {
            if (f.oneof_index) |oi| {
                try oneofs[@intCast(oi)].append(g.a, f);
            } else {
                try plain.append(g.a, f);
            }
        }

        try g.line("pub const {s} = struct {{", .{zname});

        // Oneof unions first.
        for (d.oneof_decl, 0..) |decl, oi| {
            if (oneofs[oi].items.len == 0) continue;
            const uname = try oneofUnionName(g.a, decl.name orelse return error.MalformedDescriptor);
            try g.line("    pub const {s} = union(enum) {{", .{uname});
            for (oneofs[oi].items) |f| {
                const t = try g.fieldZigType(f);
                const ptr = g.isPtrField(f);
                try g.line("        {s}: {s}{s},", .{
                    try zid(g.a, f.name orelse return error.MalformedDescriptor),
                    if (ptr) "*" else "",
                    t,
                });
            }
            try g.line("    }};", .{});
        }

        // Fields.
        for (plain.items) |f| {
            const t = try g.fieldZigType(f);
            const fname = try zid(g.a, f.name orelse return error.MalformedDescriptor);
            const is_msg = g.isPtrField(f);
            if (f.label == .LABEL_REPEATED) {
                try g.line("    {s}: []{s}{s} = &.{{}},", .{ fname, if (is_msg) "*" else "", t });
            } else if (is_msg) {
                try g.line("    {s}: ?*{s} = null,", .{ fname, t });
            } else {
                try g.line("    {s}: ?{s} = null,", .{ fname, t });
            }
        }
        for (d.oneof_decl, 0..) |decl, oi| {
            if (oneofs[oi].items.len == 0) continue;
            const dname = decl.name orelse return error.MalformedDescriptor;
            try g.line("    {s}: ?{s} = null,", .{
                try zid(g.a, dname),
                try oneofUnionName(g.a, dname),
            });
        }

        if (g.json_only) {
            try g.genJsonEncode(zname, m.fq, d, plain.items, oneofs);
            try g.genJsonDecode(zname, m.fq, d, oneofs);
        } else {
            try g.genWireCodecs(zname, d, plain.items, oneofs);
        }

        try g.line("}};", .{});
        try g.line("", .{});
    }

    /// jsonStringify, over the same traversal genEncode uses.
    ///
    /// An absent field is omitted and an empty repeated field is omitted, which
    /// is the mapping's default; presence is already explicit in the Zig type,
    /// so nothing here needs a "print defaults" mode.
    fn genJsonEncode(
        g: *Gen,
        zname: []const u8,
        fq: []const u8,
        d: *pb.DescriptorProto,
        plain: []const *pb.FieldDescriptorProto,
        oneofs: []std.ArrayList(*pb.FieldDescriptorProto),
    ) Error!void {
        try g.line("", .{});
        // One param per line, as decodeReader and encodeInto already do: the
        // flat signature passes the column limit for the longer nested names.
        try g.line("    pub fn jsonStringify(", .{});
        try g.line("        self: {s},", .{zname});
        try g.line("        jw: anytype,", .{});
        try g.line("    ) !void {{", .{});

        if (wrapper_types.has(fq)) {
            // The bare inner value, not an object around it.
            try g.line("        if (self.value) |v| {{", .{});
            try g.genJsonValue("            ", d.field[0], "v");
            try g.line("        }} else {{", .{});
            try g.line("            try jw.write(null);", .{});
            try g.line("        }}", .{});
            try g.line("    }}", .{});
            return;
        }

        if (d.field.len == 0) try g.line("        _ = self;", .{});
        try g.line("        try jw.beginObject();", .{});
        for (plain) |f| try g.genJsonField(f);
        for (d.oneof_decl, 0..) |decl, oi| {
            if (oneofs[oi].items.len == 0) continue;
            const dname = try zid(g.a, decl.name orelse return error.MalformedDescriptor);
            try g.line("        if (self.{s}) |u| switch (u) {{", .{dname});
            for (oneofs[oi].items) |f| {
                const fname = try zid(g.a, f.name orelse return error.MalformedDescriptor);
                try g.line("            .{s} => |v| {{", .{fname});
                try g.line("                try jw.objectField(\"{s}\");", .{try g.jsonName(f)});
                try g.genJsonValue("                ", f, "v");
                try g.line("            }},", .{});
            }
            try g.line("        }};", .{});
        }
        try g.line("        try jw.endObject();", .{});
        try g.line("    }}", .{});
    }

    fn genJsonField(g: *Gen, f: *pb.FieldDescriptorProto) Error!void {
        const fname = try zid(g.a, f.name orelse return error.MalformedDescriptor);
        const jname = try g.jsonName(f);
        if (g.mapEntry(f)) |entry| return g.genJsonMap(fname, jname, entry);
        if (f.label == .LABEL_REPEATED) {
            try g.line("        if (self.{s}.len != 0) {{", .{fname});
            try g.line("            try jw.objectField(\"{s}\");", .{jname});
            try g.line("            try jw.beginArray();", .{});
            try g.line("            for (self.{s}) |v| {{", .{fname});
            try g.genJsonValue("                ", f, "v");
            try g.line("            }}", .{});
            try g.line("            try jw.endArray();", .{});
            try g.line("        }}", .{});
            return;
        }
        try g.line("        if (self.{s}) |v| {{", .{fname});
        try g.line("            try jw.objectField(\"{s}\");", .{jname});
        try g.genJsonValue("            ", f, "v");
        try g.line("        }}", .{});
    }

    /// A `map<K,V>` is a JSON object, not the array of entry messages the
    /// generated representation carries. A non-string key becomes its decimal
    /// spelling, which is what the mapping says JSON object keys are.
    fn genJsonMap(
        g: *Gen,
        fname: []const u8,
        jname: []const u8,
        entry: *pb.DescriptorProto,
    ) Error!void {
        if (entry.field.len < 2) return error.MalformedDescriptor;
        const key = entry.field[0];
        const value = entry.field[1];
        try g.line("        if (self.{s}.len != 0) {{", .{fname});
        try g.line("            try jw.objectField(\"{s}\");", .{jname});
        try g.line("            try jw.beginObject();", .{});
        try g.line("            for (self.{s}) |e| {{", .{fname});
        if (key.type.? == .TYPE_STRING) {
            try g.line("                try jw.objectField(e.key orelse \"\");", .{});
        } else {
            try g.line("                var kbuf: [24]u8 = undefined;", .{});
            try g.line("                const k = std.fmt.bufPrint(", .{});
            try g.line("                    &kbuf,", .{});
            try g.line("                    \"{{d}}\",", .{});
            try g.line("                    .{{e.key orelse 0}},", .{});
            try g.line("                ) catch unreachable;", .{});
            try g.line("                try jw.objectField(k);", .{});
        }
        try g.line("                if (e.value) |v| {{", .{});
        try g.genJsonValue("                    ", value, "v");
        try g.line("                }} else {{", .{});
        try g.line("                    try jw.write(null);", .{});
        try g.line("                }}", .{});
        try g.line("            }}", .{});
        try g.line("            try jw.endObject();", .{});
        try g.line("        }}", .{});
    }

    /// One value of field `f`, already bound to `val`, at `pad` indent.
    fn genJsonValue(
        g: *Gen,
        pad: []const u8,
        f: *pb.FieldDescriptorProto,
        val: []const u8,
    ) Error!void {
        const t = f.type orelse return error.MalformedDescriptor;
        if (t == .TYPE_GROUP) return error.UnsupportedGroup;
        // A message is behind an arena pointer; std.json dispatches the hook on
        // the value, so it has to be dereferenced first.
        const deref = if (g.isPtrField(f)) ".*" else "";
        if (jsonWriteFn(t)) |fn_name| {
            try g.line("{s}try json_pb.{s}(jw, {s});", .{ pad, fn_name, val });
        } else {
            try g.line("{s}try jw.write({s}{s});", .{ pad, val, deref });
        }
    }

    /// jsonDecode, the mirror of jsonStringify.
    ///
    /// Not std.json's `jsonParseFromValue` hook: that signature carries
    /// std.json.ParseOptions, which has nowhere to put the lax/strict mode. The
    /// entry point is always a known type here, and nested messages are called
    /// by name, so the hook buys nothing.
    ///
    /// An unknown key is skipped and an explicit null reads as absent, both of
    /// which the mapping specifies.
    fn genJsonDecode(
        g: *Gen,
        zname: []const u8,
        fq: []const u8,
        d: *pb.DescriptorProto,
        oneofs: []std.ArrayList(*pb.FieldDescriptorProto),
    ) Error!void {
        _ = oneofs;
        try g.genJsonFieldTable(d);
        try g.line("", .{});
        try g.line("    pub fn jsonDecode(", .{});
        try g.line("        a: std.mem.Allocator,", .{});
        try g.line("        src: std.json.Value,", .{});
        try g.line("        o: json_pb.Options,", .{});
        try g.line("    ) json_pb.Error!*{s} {{", .{zname});
        try g.emitCall("        ", "const msg =", "try a.create", &.{zname});
        try g.line("        msg.* = .{{}};", .{});

        if (wrapper_types.has(fq)) {
            try g.line("        const inner = json_pb.wrapperInner(src);", .{});
            try g.line("        if (inner != .null) {{", .{});
            try g.genJsonRead("            ", d.field[0], "msg.value =", "inner");
            try g.line("        }}", .{});
            try g.line("        return msg;", .{});
            try g.line("    }}", .{});
            return;
        }

        if (d.field.len == 0) {
            try g.line("        _ = src;", .{});
            try g.line("        _ = o;", .{});
            try g.line("        return msg;", .{});
            try g.line("    }}", .{});
            return;
        }

        // A message whose every field is carried as std.json.Value reads the
        // value straight through, touching neither the mode nor the arena.
        var uses_options = false;
        for (d.field) |f| {
            if (!g.isJsonValue(f)) uses_options = true;
        }
        if (!uses_options) try g.line("        _ = o;", .{});

        try g.line("        const obj = switch (src) {{", .{});
        try g.line("            .object => |v| v,", .{});
        try g.line("            .null => return msg,", .{});
        try g.line("            else => return error.TypeMismatch,", .{});
        try g.line("        }};", .{});
        try g.line("        var it = obj.iterator();", .{});
        try g.line("        while (it.next()) |e| {{", .{});
        try g.line("            const v = e.value_ptr.*;", .{});
        try g.line("            if (v == .null) continue;", .{});
        try g.line("            switch (json_fields_.get(e.key_ptr.*) orelse continue) {{", .{});
        for (d.field, 0..) |f, idx| try g.genJsonDecodeCase(d, f, idx);
        try g.line("                else => {{}},", .{});
        try g.line("            }}", .{});
        try g.line("        }}", .{});
        try g.line("        return msg;", .{});
        try g.line("    }}", .{});
    }

    /// Both spellings the mapping requires a parser to accept, deduplicated
    /// because json_name equals the proto name wherever a .proto overrode it.
    fn genJsonFieldTable(g: *Gen, d: *pb.DescriptorProto) Error!void {
        if (d.field.len == 0) return;
        try g.line("", .{});
        try g.line("    const json_fields_ = std.StaticStringMap(u16).initComptime(.{{", .{});
        for (d.field, 0..) |f, idx| {
            const name = f.name orelse return error.MalformedDescriptor;
            const jname = try g.jsonName(f);
            try g.line("        .{{ \"{s}\", {d} }},", .{ jname, idx });
            if (!std.mem.eql(u8, jname, name)) {
                try g.line("        .{{ \"{s}\", {d} }},", .{ name, idx });
            }
        }
        try g.line("    }});", .{});
    }

    fn genJsonDecodeCase(
        g: *Gen,
        d: *pb.DescriptorProto,
        f: *pb.FieldDescriptorProto,
        idx: usize,
    ) Error!void {
        const fname = try zid(g.a, f.name orelse return error.MalformedDescriptor);
        try g.line("                {d} => {{", .{idx});
        defer_block: {
            if (g.mapEntry(f)) |entry| {
                try g.genJsonDecodeMap(fname, entry, try g.fieldZigType(f));
                break :defer_block;
            }
            if (f.label == .LABEL_REPEATED) {
                try g.genJsonDecodeRepeated(f, fname);
                break :defer_block;
            }
            if (f.oneof_index) |oi| {
                const decl = d.oneof_decl[@intCast(oi)];
                const dname = try zid(g.a, decl.name orelse return error.MalformedDescriptor);
                try g.genJsonRead("                    ", f, "const val_ =", "v");
                const assign = try std.fmt.allocPrint(
                    g.a,
                    "                    msg.{s} = .{{ .{s} = val_ }};",
                    .{ dname, fname },
                );
                if (assign.len <= max_cols) {
                    try g.line("{s}", .{assign});
                } else {
                    try g.line("                    msg.{s} = .{{", .{dname});
                    try g.line("                        .{s} = val_,", .{fname});
                    try g.line("                    }};", .{});
                }
                break :defer_block;
            }
            try g.genJsonRead(
                "                    ",
                f,
                try std.fmt.allocPrint(g.a, "msg.{s} =", .{fname}),
                "v",
            );
        }
        try g.line("                }},", .{});
    }

    fn genJsonDecodeRepeated(
        g: *Gen,
        f: *pb.FieldDescriptorProto,
        fname: []const u8,
    ) Error!void {
        const elem = try g.fieldZigType(f);
        const ptr = if (g.isPtrField(f)) "*" else "";
        try g.line("                    const arr_ = try json_pb.asArray(a, v, o);", .{});
        const elem_type = try std.fmt.allocPrint(g.a, "{s}{s}", .{ ptr, elem });
        try g.emitCall(
            "                    ",
            "const items_ =",
            "try a.alloc",
            &.{ elem_type, "arr_.len" },
        );
        try g.line("                    for (arr_, 0..) |item_, i_| {{", .{});
        try g.genJsonRead("                        ", f, "items_[i_] =", "item_");
        try g.line("                    }}", .{});
        try g.line("                    msg.{s} = items_;", .{fname});
    }

    fn genJsonDecodeMap(
        g: *Gen,
        fname: []const u8,
        entry: *pb.DescriptorProto,
        entry_type: []const u8,
    ) Error!void {
        if (entry.field.len < 2) return error.MalformedDescriptor;
        const key = entry.field[0];
        const value = entry.field[1];
        try g.line("                    if (v != .object) return error.TypeMismatch;", .{});
        try g.line("                    const items_ = try a.alloc(", .{});
        try g.line("                        *{s},", .{entry_type});
        try g.line("                        v.object.count(),", .{});
        try g.line("                    );", .{});
        try g.line("                    var mit_ = v.object.iterator();", .{});
        try g.line("                    var i_: usize = 0;", .{});
        try g.line("                    while (mit_.next()) |me_| : (i_ += 1) {{", .{});
        try g.emitCall("                        ", "const en_ =", "try a.create", &.{entry_type});
        try g.line("                        en_.* = .{{}};", .{});
        if (key.type.? == .TYPE_STRING) {
            try g.line("                        en_.key = me_.key_ptr.*;", .{});
        } else {
            const read = try jsonReadFn(key.type.?);
            try g.line("                        en_.key = try json_pb.{s}(", .{read});
            try g.line("                            .{{ .string = me_.key_ptr.* }},", .{});
            try g.line("                            o,", .{});
            try g.line("                        );", .{});
        }
        // A null value stays absent, the same rule the field loop applies. The
        // message decoders answer a JSON null with an empty message, which
        // would turn `{"k":null}` into `{"k":{}}` on the way back out.
        try g.line("                        if (me_.value_ptr.* != .null) {{", .{});
        try g.genJsonRead(
            "                            ",
            value,
            "en_.value =",
            "me_.value_ptr.*",
        );
        try g.line("                        }}", .{});
        try g.line("                        items_[i_] = en_;", .{});
        try g.line("                    }}", .{});
        try g.line("                    msg.{s} = items_;", .{fname});
    }

    /// `{pad}{dest} {callee}(args...);`, one argument per line when the flat
    /// form passes the column limit. Nested message names reach past it on
    /// their own, so this is not an edge case.
    fn emitCall(
        g: *Gen,
        pad: []const u8,
        dest: []const u8,
        callee: []const u8,
        args: []const []const u8,
    ) Error!void {
        var flat: std.ArrayList(u8) = .empty;
        try flat.appendSlice(g.a, pad);
        if (dest.len > 0) {
            try flat.appendSlice(g.a, dest);
            try flat.append(g.a, ' ');
        }
        try flat.appendSlice(g.a, callee);
        try flat.append(g.a, '(');
        for (args, 0..) |arg, i| {
            if (i > 0) try flat.appendSlice(g.a, ", ");
            try flat.appendSlice(g.a, arg);
        }
        try flat.appendSlice(g.a, ");");
        if (flat.items.len <= max_cols) {
            try g.line("{s}", .{flat.items});
            return;
        }
        if (dest.len == 0) {
            try g.line("{s}{s}(", .{ pad, callee });
            for (args) |arg| try g.line("{s}    {s},", .{ pad, arg });
            try g.line("{s});", .{pad});
            return;
        }
        // The header alone can pass the limit once a nested message name is
        // both the destination and the callee.
        if (pad.len + dest.len + 1 + callee.len + 1 <= max_cols) {
            try g.line("{s}{s} {s}(", .{ pad, dest, callee });
            for (args) |arg| try g.line("{s}    {s},", .{ pad, arg });
            try g.line("{s});", .{pad});
            return;
        }
        try g.line("{s}{s}", .{ pad, dest });
        try g.line("{s}    {s}(", .{ pad, callee });
        for (args) |arg| try g.line("{s}        {s},", .{ pad, arg });
        try g.line("{s}    );", .{pad});
    }

    /// `dest` is a full left-hand side, e.g. "msg.kind =" or "items_[i_] =".
    fn genJsonRead(
        g: *Gen,
        pad: []const u8,
        f: *pb.FieldDescriptorProto,
        dest: []const u8,
        val: []const u8,
    ) Error!void {
        const t = f.type orelse return error.MalformedDescriptor;
        if (t == .TYPE_GROUP) return error.UnsupportedGroup;
        if (g.isJsonValue(f)) {
            try g.line("{s}{s} {s};", .{ pad, dest, val });
            return;
        }
        switch (t) {
            .TYPE_MESSAGE => {
                const callee = try std.fmt.allocPrint(
                    g.a,
                    "try {s}.jsonDecode",
                    .{try g.typeName(f)},
                );
                try g.emitCall(pad, dest, callee, &.{ "a", val, "o" });
            },
            .TYPE_ENUM => try g.emitCall(
                pad,
                dest,
                "try json_pb.asEnum",
                &.{ try g.typeName(f), val, "o" },
            ),
            else => {
                const callee = try std.fmt.allocPrint(
                    g.a,
                    "try json_pb.{s}",
                    .{try jsonReadFn(t)},
                );
                const args: []const []const u8 = if (jsonReadTakesAlloc(t))
                    &.{ "a", val, "o" }
                else
                    &.{ val, "o" };
                try g.emitCall(pad, dest, callee, args);
            },
        }
    }

    fn genWireCodecs(
        g: *Gen,
        zname: []const u8,
        d: *pb.DescriptorProto,
        plain: []const *pb.FieldDescriptorProto,
        oneofs: []std.ArrayList(*pb.FieldDescriptorProto),
    ) Error!void {
        // decode() entry point and decodeReader().
        try g.line("", .{});
        // Params go one per line: message names reach 48 characters, so the
        // flat signature blows the column limit for most of the 510 messages.
        // The trailing comma is what keeps zig fmt from folding it back.
        try g.line("    pub fn decode(", .{});
        try g.line("        a: std.mem.Allocator,", .{});
        try g.line("        buf: []const u8,", .{});
        try g.line("    ) wire.DecodeError!*{s} {{", .{zname});
        try g.line("        var r = wire.Reader.init(buf);", .{});
        try g.line("        return decodeReader(a, &r);", .{});
        try g.line("    }}", .{});
        try g.line("", .{});
        // Not pub: every caller (decode() and the nested-message cases of
        // sibling messages) lives in this same file, and `pub` only gates
        // access from other files.
        try g.line("    fn decodeReader(", .{});
        try g.line("        a: std.mem.Allocator,", .{});
        try g.line("        r: *wire.Reader,", .{});
        try g.line("    ) wire.DecodeError!*{s} {{", .{zname});
        try g.emitCall("        ", "const msg =", "try a.create", &.{zname});
        try g.line("        msg.* = .{{}};", .{});

        for (plain) |f| {
            if (f.label != .LABEL_REPEATED) continue;
            const t = try g.fieldZigType(f);
            const ptr = if (f.type.? == .TYPE_MESSAGE) "*" else "";
            const flat = "        var list_: std.ArrayList() = .empty;".len +
                f.name.?.len + ptr.len + t.len;
            if (flat <= max_cols) {
                try g.line("        var list_{s}: std.ArrayList({s}{s}) = .empty;", .{
                    f.name.?,
                    ptr,
                    t,
                });
            } else {
                try g.line("        var list_{s}: std.ArrayList(", .{f.name.?});
                try g.line("            {s}{s},", .{ ptr, t });
                try g.line("        ) = .empty;", .{});
            }
        }

        // `while ... switch` rather than a switch nested in a block: one less
        // indent level, which is 4 columns back for every line of every case.
        try g.line("        while (try r.next()) |tag| switch (tag.field) {{", .{});
        for (d.field) |f| try g.genFieldCase(d, f);
        try g.line("            else => try r.skip(tag.wire),", .{});
        try g.line("        }};", .{});

        for (plain) |f| {
            if (f.label != .LABEL_REPEATED) continue;
            const fname = try zid(g.a, f.name.?);
            const flat = "        msg. = try list_.toOwnedSlice(a);".len + fname.len + f.name.?.len;
            if (flat <= max_cols) {
                try g.line("        msg.{s} = try list_{s}.toOwnedSlice(a);", .{ fname, f.name.? });
            } else {
                try g.line("        msg.{s} =", .{fname});
                try g.line("            try list_{s}.toOwnedSlice(a);", .{f.name.?});
            }
        }
        try g.line("        return msg;", .{});
        try g.line("    }}", .{});

        try g.genEncode(zname, d, plain, oneofs);
    }

    /// encode() / encodeInto(), the mirror of decode() / decodeReader().
    ///
    /// Fields are emitted in declaration order rather than sorted by number.
    /// Protobuf explicitly allows any field order on the wire, and every decoder
    /// including this one dispatches on the tag, so the only thing sorting would
    /// buy is byte-identity with protoc — which nothing here depends on.
    ///
    /// A singular field is written only when it is non-null, so a value that
    /// decode() left absent stays absent through a re-encode. That is what makes
    /// `decode(encode(x))` equal x rather than merely equivalent to it.
    fn genEncode(
        g: *Gen,
        zname: []const u8,
        d: *pb.DescriptorProto,
        plain: []const *pb.FieldDescriptorProto,
        oneofs: []std.ArrayList(*pb.FieldDescriptorProto),
    ) Error!void {
        try g.line("", .{});
        try g.line("    pub fn encode(", .{});
        try g.line("        self: *const {s},", .{zname});
        try g.line("        a: std.mem.Allocator,", .{});
        try g.line("    ) wire.EncodeError![]u8 {{", .{});
        try g.line("        var w = wire.Writer.init(a);", .{});
        try g.line("        errdefer w.deinit();", .{});
        try g.line("        try self.encodeInto(&w);", .{});
        try g.line("        return w.toOwnedSlice();", .{});
        try g.line("    }}", .{});
        try g.line("", .{});
        // Not pub, for the same reason decodeReader is not: every caller is a
        // sibling message in this file.
        try g.line("    fn encodeInto(", .{});
        try g.line("        self: *const {s},", .{zname});
        try g.line("        w: *wire.Writer,", .{});
        try g.line("    ) wire.EncodeError!void {{", .{});

        // A message that exists only to namespace nested enums has no fields,
        // so neither parameter is read. decodeReader has no equivalent problem:
        // it always creates the message and always loops over the reader.
        if (d.field.len == 0) {
            try g.line("        _ = self;", .{});
            try g.line("        _ = w;", .{});
        }

        for (plain) |f| try g.genFieldWrite(f);

        for (d.oneof_decl, 0..) |decl, oi| {
            if (oneofs[oi].items.len == 0) continue;
            const dname = try zid(g.a, decl.name orelse return error.MalformedDescriptor);
            try g.line("        if (self.{s}) |u| switch (u) {{", .{dname});
            for (oneofs[oi].items) |f| {
                const fname = try zid(g.a, f.name orelse return error.MalformedDescriptor);
                try g.line("            .{s} => |v| {{", .{fname});
                try g.genWriteValue("                ", f, "v");
                try g.line("            }},", .{});
            }
            try g.line("        }};", .{});
        }

        try g.line("    }}", .{});
    }

    fn genFieldWrite(g: *Gen, f: *pb.FieldDescriptorProto) Error!void {
        const name = f.name orelse return error.MalformedDescriptor;
        const fname = try zid(g.a, name);
        const number = f.number orelse return error.MalformedDescriptor;
        const t = f.type orelse return error.MalformedDescriptor;

        if (f.label != .LABEL_REPEATED) {
            try g.line("        if (self.{s}) |v| {{", .{fname});
            try g.genWriteValue("            ", f, "v");
            try g.line("        }}", .{});
            return;
        }

        // Repeated. Packable scalars go out packed, which is proto3's default
        // and what protoc emits; the decoder above accepts either form.
        //
        // Enums deliberately do NOT: `isPackable` excludes them, so the decoder
        // only ever reads a repeated enum unpacked, and emitting packed here
        // would produce output this very file cannot read back.
        if (isPackable(t)) {
            try g.line("        if (self.{s}.len != 0) {{", .{fname});
            try g.line("            const mark = try w.beginLen({d});", .{number});
            try g.line("            for (self.{s}) |v| try w.{s}({s}v{s});", .{
                fname,
                try scalarWriteRaw(t),
                scalarWriteCast(t),
                scalarWriteCastClose(t),
            });
            try g.line("            try w.endLen(mark);", .{});
            try g.line("        }}", .{});
            return;
        }
        try g.line("        for (self.{s}) |v| {{", .{fname});
        try g.genWriteValue("            ", f, "v");
        try g.line("        }}", .{});
    }

    /// One value of field `f`, already bound to `val`, at `pad` indent.
    fn genWriteValue(
        g: *Gen,
        pad: []const u8,
        f: *pb.FieldDescriptorProto,
        val: []const u8,
    ) Error!void {
        const number = f.number orelse return error.MalformedDescriptor;
        const t = f.type orelse return error.MalformedDescriptor;
        switch (t) {
            .TYPE_MESSAGE => {
                try g.line("{s}const mark = try w.beginLen({d});", .{ pad, number });
                try g.line("{s}try {s}.encodeInto(w);", .{ pad, val });
                try g.line("{s}try w.endLen(mark);", .{pad});
            },
            .TYPE_ENUM => try g.line("{s}try w.writeInt32({d}, @backingInt({s}));", .{
                pad,
                number,
                val,
            }),
            .TYPE_GROUP => return error.UnsupportedGroup,
            else => {
                const call = try std.fmt.allocPrint(g.a, "try w.{s}({d}, {s}{s}{s});", .{
                    try scalarWrite(t),
                    number,
                    scalarWriteCast(t),
                    val,
                    scalarWriteCastClose(t),
                });
                if (pad.len + call.len <= max_cols) {
                    try g.line("{s}{s}", .{ pad, call });
                } else {
                    try g.line("{s}try w.{s}(", .{ pad, try scalarWrite(t) });
                    try g.line("{s}    {d},", .{ pad, number });
                    try g.line("{s}    {s}{s}{s},", .{
                        pad,
                        scalarWriteCast(t),
                        val,
                        scalarWriteCastClose(t),
                    });
                    try g.line("{s});", .{pad});
                }
            },
        }
    }

    fn genFieldCase(g: *Gen, d: *pb.DescriptorProto, f: *pb.FieldDescriptorProto) Error!void {
        const number = f.number orelse return error.MalformedDescriptor;
        const name = f.name orelse return error.MalformedDescriptor;
        const t = f.type orelse return error.MalformedDescriptor;
        const is_oneof = f.oneof_index != null;

        try g.line("            {d} => {{", .{number});
        if (f.label == .LABEL_REPEATED and !is_oneof) {
            if (isPackable(t)) {
                // Accept both packed and unpacked encodings.
                try g.line("                if (tag.wire == .len) {{", .{});
                try g.line("                    var sub = try r.subReader();", .{});
                try g.line("                    while (!sub.atEnd()) {{", .{});
                try g.genAppend("                        ", name, try scalarRead(g.a, t, "sub"));
                try g.line("                    }}", .{});
                try g.line("                }} else {{", .{});
                try g.genAppend("                    ", name, try scalarRead(g.a, t, "r"));
                try g.line("                }}", .{});
            } else if (t == .TYPE_MESSAGE) {
                try g.line("                var sub = try r.subReader();", .{});
                try g.genSubDecode(f);
                try g.genAppend("                ", name, "v");
            } else if (t == .TYPE_ENUM) {
                try g.genEnumRead(f, "r");
                try g.genAppend("                ", name, "v");
            } else { // string/bytes
                try g.genAppend("                ", name, try g.readExpr(f));
            }
        } else {
            // Message and enum reads land in a local first: the flat statement
            // carries both the field name and a type name, and the longer ones
            // run past the column limit.
            const val = switch (t) {
                .TYPE_MESSAGE => blk: {
                    try g.line("                var sub = try r.subReader();", .{});
                    try g.genSubDecode(f);
                    break :blk "v";
                },
                .TYPE_ENUM => blk: {
                    try g.genEnumRead(f, "r");
                    break :blk "v";
                },
                else => try g.readExpr(f),
            };
            if (is_oneof) {
                const oname = try zid(g.a, d.oneof_decl[@intCast(f.oneof_index.?)].name orelse
                    return error.MalformedDescriptor);
                const fname = try zid(g.a, name);
                const flat = "                msg. = .{ . =  };".len + oname.len + fname.len + val.len;
                if (flat <= max_cols) {
                    try g.line("                msg.{s} = .{{ .{s} = {s} }};", .{ oname, fname, val });
                } else {
                    // Some oneof member names are themselves ~60 characters.
                    try g.line("                msg.{s} = .{{", .{oname});
                    try g.line("                    .{s} = {s},", .{ fname, val });
                    try g.line("                }};", .{});
                }
            } else {
                try g.line("                msg.{s} = {s};", .{ try zid(g.a, name), val });
            }
        }
        try g.line("            }},", .{});
    }

    /// `const v = try <Type>.decodeReader(a, &sub);` at case-body indent,
    /// split across lines when the type name alone would overflow. The
    /// trailing comma survives the `zig fmt` pass that follows generation.
    fn genSubDecode(g: *Gen, f: *pb.FieldDescriptorProto) Error!void {
        const tname = try g.typeName(f);
        const flat = "                const v = try ".len + tname.len + ".decodeReader(a, &sub);".len;
        if (flat <= max_cols) {
            try g.line("                const v = try {s}.decodeReader(a, &sub);", .{tname});
        } else {
            try g.line("                const v = try {s}.decodeReader(", .{tname});
            try g.line("                    a,", .{});
            try g.line("                    &sub,", .{});
            try g.line("                );", .{});
        }
    }

    /// `const v: <Enum> = @fromBackingInt(try <recv>.readInt32());`, broken after
    /// the `=` when the enum name is too long to fit beside it.
    fn genEnumRead(g: *Gen, f: *pb.FieldDescriptorProto, recv: []const u8) Error!void {
        const tname = try g.typeName(f);
        const flat = "                const v:  = @fromBackingInt(try .readInt32());".len +
            tname.len + recv.len;
        if (flat <= max_cols) {
            try g.line("                const v: {s} = @fromBackingInt(try {s}.readInt32());", .{
                tname,
                recv,
            });
        } else if ("                const v:  =".len + tname.len <= max_cols) {
            try g.line("                const v: {s} =", .{tname});
            try g.line("                    @fromBackingInt(try {s}.readInt32());", .{recv});
        } else {
            // Enum names run to 71 characters, past what even a bare `const
            // v: <Enum> =` fits; only @as puts the name on a line of its own.
            try g.line("                const v = @as(", .{});
            try g.line("                    {s},", .{tname});
            try g.line("                    @fromBackingInt(try {s}.readInt32()),", .{recv});
            try g.line("                );", .{});
        }
    }

    /// `try list_<name>.append(a, <val>);` at `pad` indent, argument-wrapped
    /// when the list name and value together overflow.
    fn genAppend(g: *Gen, pad: []const u8, name: []const u8, val: []const u8) Error!void {
        const flat = pad.len + "try list_.append(a, );".len + name.len + val.len;
        if (flat <= max_cols) {
            try g.line("{s}try list_{s}.append(a, {s});", .{ pad, name, val });
        } else {
            try g.line("{s}try list_{s}.append(", .{ pad, name });
            try g.line("{s}    a,", .{pad});
            try g.line("{s}    {s},", .{ pad, val });
            try g.line("{s});", .{pad});
        }
    }
};

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.order(u8, a, b) == .lt;
}

/// `--name=value` -> value; anything else -> null. Same shape as the emulator's
/// own flag parsing in entrypoints/server.zig.
fn flagValue(arg: []const u8, name: []const u8) ?[]const u8 {
    if (!std.mem.startsWith(u8, arg, name)) return null;
    const rest = arg[name.len..];
    if (rest.len == 0 or rest[0] != '=') return null;
    return rest[1..];
}

pub fn main(init: std.process.Init) !void {
    var stderr_buf: [4096]u8 = undefined;
    var stderr_writer = std.Io.File.stderr().writerStreaming(init.io, &stderr_buf);
    const err_out = &stderr_writer.interface;

    var arena_state = std.heap.ArenaAllocator.init(std.heap.smp_allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.next();
    const fdset_path = args.next() orelse {
        try err_out.writeAll("usage: gen-proto <googlesql.fdset> <out.zig>\n");
        try err_out.flush();
        std.process.exit(2);
    };
    const out_path = args.next() orelse {
        try err_out.writeAll("usage: gen-proto <googlesql.fdset> <out.zig>\n");
        try err_out.flush();
        std.process.exit(2);
    };
    // Optional, because the second fdset's output lives in the server module,
    // which cannot reach src/proto/wire.zig by relative path: a file reached
    // that way joins the importing module, and wire.zig is already in the
    // engine's. It has to come through the `zigquery` module import instead.
    var wire_import: []const u8 = "@import(\"wire.zig\")";
    var desc: []const u8 = "Plain-struct codecs for the googlesql resolved AST protos.";
    // The header names the .fdset, but `addFileArg` hands us an absolute path,
    // which would make the generated file differ per machine and break the
    // gen-proto-drift CI job. The caller passes the repo-relative label.
    var source: []const u8 = "proto/googlesql.fdset";
    // Emitted instead of the wire import under --json-only.
    var json_import: []const u8 = "@import(\"../json_pb.zig\")";
    var json_only = false;
    var roots: std.ArrayList([]const u8) = .empty;
    while (args.next()) |arg| {
        if (flagValue(arg, "--roots")) |v| {
            var it = std.mem.splitScalar(u8, v, ',');
            while (it.next()) |name| {
                const trimmed = std.mem.trim(u8, name, " ");
                if (trimmed.len > 0) try roots.append(arena, trimmed);
            }
        } else if (std.mem.eql(u8, arg, "--json-only")) {
            json_only = true;
        } else if (flagValue(arg, "--json-import")) |v| {
            json_import = v;
        } else if (flagValue(arg, "--wire-import")) |v| {
            wire_import = v;
        } else if (flagValue(arg, "--desc")) |v| {
            desc = v;
        } else if (flagValue(arg, "--source")) |v| {
            source = v;
        } else {
            try err_out.print("unknown flag: {s}\n", .{arg});
            try err_out.flush();
            std.process.exit(2);
        }
    }

    const bytes = try std.Io.Dir.cwd().readFileAlloc(init.io, fdset_path, arena, .limited(1 << 26));
    const fds = try pb.FileDescriptorSet.decode(arena, bytes);

    var g: Gen = .{ .a = arena, .json_only = json_only };
    try g.collect(fds);
    // Before resolveNames, so the collision qualification reflects what is
    // actually emitted rather than everything --include_imports dragged in.
    if (roots.items.len > 0) g.prune(roots.items) catch |err| switch (err) {
        error.UnknownRoot => {
            try err_out.writeAll("--roots names a message this .fdset does not define\n");
            try err_out.flush();
            std.process.exit(2);
        },
        else => return err,
    };
    try g.resolveNames();

    std.mem.sort([]const u8, g.msg_keys.items, {}, lessThan);
    std.mem.sort([]const u8, g.enum_keys.items, {}, lessThan);

    try g.line("//! GENERATED by tools/gen_proto.zig from {s} — do not edit.", .{source});
    try g.line("//! {s}", .{desc});
    try g.line("", .{});
    try g.line("const std = @import(\"std\");", .{});
    if (json_only) {
        try g.line("const json_pb = {s};", .{json_import});
    } else {
        try g.line("pub const wire = {s};", .{wire_import});
    }
    try g.line("", .{});
    for (g.enum_keys.items) |fq| try g.genEnum(g.enums.get(fq).?);
    for (g.msg_keys.items) |fq| try g.genMessage(g.msgs.get(fq).?);

    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = out_path, .data = g.out.items });
    try err_out.print("wrote {s}: {d} messages, {d} enums\n", .{
        out_path,
        g.msg_keys.items.len,
        g.enum_keys.items.len,
    });
    try err_out.flush();
}
